const EXACT = new Map<string, string>()
const PATTERNS: { re: RegExp; names: string[]; zh: string }[] = []

const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

for (const [en, zh] of PAIRS) {
  if (!/\{(what|n)\}/.test(en)) {
    EXACT.set(en, zh)
    continue
  }
  const names: string[] = []
  const source = escape(en).replace(/\\\{(what|n)\\\}/g, (_, name: string) => {
    names.push(name)

    return name === 'n' ? '(\\d+)' : '(.+?)'
  })
  PATTERNS.push({ re: new RegExp(`^${source}$`), names, zh })
}

const normal = (text: string) => text.replace(/\s+/g, ' ').trim()

const seen = new Map<string, string>()

// The caption for a line a scene said; '' when the line has no translation.
export function captionFor(line: string): string {
  const text = normal(line)
  const hit = seen.get(text)
  if (hit !== undefined) return hit
  let found = EXACT.get(text) ?? ''
  if (!found) {
    for (const { re, names, zh } of PATTERNS) {
      const m = re.exec(text)
      if (!m) continue
      const values: Record<string, string> = {}
      names.forEach((name, i) => {
        values[name] ??= m[i + 1] ?? ''
      })
      found = zh.replace(/\{(what|n)\}/g, (_, name: string) => values[name] ?? '')
      break
    }
  }
  if (seen.size >= 500) seen.clear()
  seen.set(text, found)

  return found
}

// The captions for the lines said this frame as one line at most `cols`
// terminal columns wide (a Chinese character takes two), cut with an ellipsis.
export function captionLine(lines: string[], cols: number): string {
  const text = lines.map(captionFor).filter(Boolean).join(' / ')
  let used = 0
  let out = ''
  for (const c of text) {
    const w = /[ -~]/.test(c) ? 1 : 2
    if (used + w > cols - 2) return `${out}…`
    used += w
    out += c
  }

  return out
}

